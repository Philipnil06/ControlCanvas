def _validate_generated_html(html):
    """Protect demo reliability by capping model-generated code size."""
    if not isinstance(html, str) or not html.strip():
        return _error("Empty model response", "No HTML returned", status=502)
    if len(html) > MAX_GENERATED_CODE_LEN:
        return _error(
            "Model output too long",
            f"Generated code too long (max {MAX_GENERATED_CODE_LEN} chars)",
            status=502,
        )
    return None


def _error(error, details="", status=400, extra=None):
    payload = {"ok": False, "error": str(error), "details": str(details or "")}
    if extra:
        payload.update(extra)
    return status, payload


def _validate_input(mode, user_prompt, generated_code):
    if mode in ("builder", "safe_builder", "sim_builder"):
        if not user_prompt.strip():
            return _error("Invalid input", "Prompt cannot be empty", status=400)
        if len(user_prompt) > MAX_PROMPT_LEN:
            return _error(
                "Invalid input",
                f"Prompt too long (max {MAX_PROMPT_LEN} chars)",
                status=400,
            )
    elif mode in ("inspector", "sim_inspector"):
        if not user_prompt.strip():
            return _error("Invalid input", "Prompt cannot be empty", status=400)
        if len(user_prompt) > MAX_PROMPT_LEN:
            return _error(
                "Invalid input",
                f"Prompt too long (max {MAX_PROMPT_LEN} chars)",
                status=400,
            )
        if not generated_code.strip():
            return _error("Invalid input", "Generated code cannot be empty", status=400)
        if len(generated_code) > MAX_GENERATED_CODE_LEN:
            return _error(
                "Invalid input",
                f"Generated code too long (max {MAX_GENERATED_CODE_LEN} chars)",
                status=400,
            )
    else:
        return _error(
            "Invalid mode",
            "Use builder, safe_builder, inspector, sim_builder, or sim_inspector",
            status=400,
        )
    return None


